#!/usr/bin/env python3
"""Build the data image for the AquesTalk10 port.

The recompiled machine-code translation in decomp.c refers to the original
library's global data by address (Ghidra shows the PIE at base 0x100000).
We therefore reproduce the library's data layout inside a wasm/native
byte array:

    image offset = original VMA - 0x100000

Only the read-only data (.rodata, which holds all voice/unit tables and the
kana dictionaries) and the writable data segment (.data.rel.ro, .got, .data)
are needed.  The original .text is *not* copied: every function is real
recompiled C code.

R_X86_64_RELATIVE dynamic relocations are preserved and applied at startup,
turning the embedded 64-bit slots into pointers into aq_image.
"""
import struct
import os

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.abspath(os.path.join(HERE, '..', '..'))
SO = os.path.join(ROOT, 'aqtk10_lnx', 'lib64', 'libAquesTalk10.so.1.1')
OUT = os.path.join(ROOT, 'port', 'src', 'image.c')

BASE = 0x100000              # Ghidra image base for this PIE
IMAGE_SIZE = 0x25cf80        # end of .bss (raw VMA)

d = open(SO, 'rb').read()

# --- section table ------------------------------------------------------
e_shoff = struct.unpack_from('<Q', d, 0x28)[0]
e_shentsize = struct.unpack_from('<H', d, 0x3a)[0]
e_shnum = struct.unpack_from('<H', d, 0x3c)[0]
e_shstrndx = struct.unpack_from('<H', d, 0x3e)[0]
shstr = struct.unpack_from('<Q', d, e_shoff + e_shstrndx * e_shentsize + 0x18)[0]
secs = {}
for i in range(e_shnum):
    o = e_shoff + i * e_shentsize
    no = struct.unpack_from('<I', d, o)[0]
    name = d[shstr + no:].split(b'\0')[0].decode()
    addr, off, size = struct.unpack_from('<QQQ', d, o + 0x10)
    secs[name] = (addr, off, size)

ro_addr, ro_off, ro_size = secs['.rodata']
# The RW PT_LOAD starts at file offset 0x5a000 with VMA 0x25a000 and covers
# .ctors .. .bss.  We copy the file-backed part only.
rw_addr = 0x25a000
rw_off = 0x5a000
rw_size = 0x25cf68 - rw_addr      # file-backed up to start of .bss

ro = d[ro_off:ro_off + ro_size]
rw = d[rw_off:rw_off + rw_size]


def emit_bytes(f, name, data, extra=''):
    f.write('__attribute__((aligned(64))) const unsigned char %s[%d] = {\n'
            % (name, len(data)))
    for i in range(0, len(data), 24):
        f.write('  ' + ','.join('0x%02x' % b for b in data[i:i + 24]) + ',\n')
    f.write('};\n%s\n' % extra)

# --- dynamic relocations -------------------------------------------------
rel_addr, rel_off, rel_size = secs['.rela.dyn']
relocs = []
for i in range(rel_size // 24):
    off, info, add = struct.unpack_from('<QQq', d, rel_off + i * 24)
    if (info & 0xffffffff) == 8:          # R_X86_64_RELATIVE
        relocs.append((off, add))

os.makedirs(os.path.dirname(OUT), exist_ok=True)
with open(OUT, 'w') as f:
    f.write('/* Generated by tools/gen_image.py -- do not edit. */\n')
    f.write('#include "shim.h"\n\n')
    f.write('#define AQ_RO_OFF 0x%x\n#define AQ_RW_OFF 0x%x\n#define AQ_IMAGE_SIZE 0x%x\n' % (ro_addr, rw_addr, IMAGE_SIZE))
    emit_bytes(f, 'aq_rodata', ro)
    emit_bytes(f, 'aq_rwdata', rw)
    f.write('const AqReloc aq_relocs[] = {\n')
    for off, add in relocs:
        f.write('  {0x%x, 0x%x},\n' % (off, add))
    f.write('};\nconst unsigned aq_num_relocs = %d;\n\n' % len(relocs))
    f.write('__attribute__((aligned(64))) unsigned char aq_image[AQ_IMAGE_SIZE];\n\n')
    f.write('''
static int aq_image_ready;

void aq_load_image(void)
{
    unsigned i;
    if (aq_image_ready)
        return;
    aq_image_ready = 1;
    memcpy(aq_image + AQ_RO_OFF, aq_rodata, sizeof(aq_rodata));
    memcpy(aq_image + AQ_RW_OFF, aq_rwdata, sizeof(aq_rwdata));
    for (i = 0; i < aq_num_relocs; i++) {
        uintptr_t base = (uintptr_t)aq_image;
        *(unsigned long long *)(aq_image + aq_relocs[i].off) =
            (unsigned long long)(base + aq_relocs[i].addend);
    }
}

__attribute__((constructor)) static void aq_image_ctor(void)
{
    aq_load_image();
}
''')

print('wrote %s' % OUT)
print('  rodata  %#x bytes @ image+%#x' % (len(ro), ro_addr))
print('  rwdata  %#x bytes @ image+%#x' % (len(rw), rw_addr))
print('  relocs  %d, image %#x bytes' % (len(relocs), IMAGE_SIZE))
