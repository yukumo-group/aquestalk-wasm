#!/usr/bin/env python3
"""Embed the data segments of libAquesTalk2Eva.so.2.3 and its dynamic relocations.

Only *data* is embedded: .rodata (contains the built-in phont, all lookup
tables and strings) plus the writable segment (.ctors/.data.rel.ro/.got/.data).
The machine code is NOT embedded -- that is recompiled from Ghidra's C output
(see gen_decomp.py).  Addresses inside the generated code are absolute
virtual addresses of the original ELF; `aq_image` is a byte array that mirrors
that address space, so `DAT_0011xxxx` is simply `aq_image + 0x11xxxx`.

The original file is an ET_DYN with two PT_LOAD segments whose virtual
addresses are 0 and 0x216670 respectively.  The second segment is therefore
*not* at its file offset; the helper below places every byte at its VMA.
"""
import os
import struct
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.abspath(os.path.join(HERE, '..', '..'))
SO = os.path.join(ROOT, 'aqtk2-lnx', 'lib64', 'libAquesTalk2Eva.so.2.3')
OUT = os.path.join(ROOT, 'port', 'src', 'image.c')

IMAGE_SIZE = 0x217038          # end of the RW PT_LOAD (vaddr 0x216670 + 0x9c8)


def parse_sections(d):
    e_shoff = struct.unpack_from('<Q', d, 0x28)[0]
    e_shentsize = struct.unpack_from('<H', d, 0x3a)[0]
    e_shnum = struct.unpack_from('<H', d, 0x3c)[0]
    e_shstrndx = struct.unpack_from('<H', d, 0x3e)[0]
    shstr = struct.unpack_from('<Q', d, e_shoff + e_shstrndx * e_shentsize + 0x18)[0]
    secs = {}
    for i in range(e_shnum):
        o = e_shoff + i * e_shentsize
        name_off = struct.unpack_from('<I', d, o)[0]
        name = d[shstr + name_off:].split(b'\0')[0].decode()
        addr, off, size = struct.unpack_from('<QQQ', d, o + 0x10)
        secs[name] = (addr, off, size)
    return secs, (e_shoff, e_shentsize, e_shnum)


def parse_dynsym(d, secs):
    dynsym_addr, dynsym_off, dynsym_size = secs['.dynsym']
    dynstr_addr, dynstr_off, _ = secs['.dynstr']
    out = []
    # number of symbols: derive from relocations (max index) plus a bound
    for i in range(dynsym_size // 24):
        o = dynsym_off + i * 24
        if o + 24 > len(d):
            break
        st_name, st_info, st_other, st_shndx, st_value, st_size = struct.unpack_from('<IBBHQQ', d, o)
        name = d[dynstr_off + st_name:].split(b'\0')[0].decode('latin-1') if st_name else ''
        if st_info == 0 and st_name == 0:
            out.append(('', 0))
            continue
        out.append((name, st_value))
    return out


def c_array(name, data, static=True):
    lines = ['%sconst unsigned char %s[%d] = {' % ('static ' if static else '', name, len(data))]
    for i in range(0, len(data), 16):
        lines.append('  ' + ','.join('0x%02x' % b for b in data[i:i + 16]) + ',')
    lines.append('};')
    return '\n'.join(lines)


def main():
    d = open(SO, 'rb').read()
    secs, _ = parse_sections(d)
    syms = parse_dynsym(d, secs)

    # data that must be present in the image
    ro_addr, ro_off, ro_size = secs['.rodata']
    rw_addr, rw_off, rw_size = secs['.ctors']
    assert rw_addr == 0x216670, hex(rw_addr)
    assert ro_addr == ro_off
    rw_end = 0x217028            # .data ends here; .bss is zero filled
    rw_len = rw_end - rw_addr

    rodata = d[ro_off:ro_off + ro_size]
    rwdata = d[rw_off:rw_off + rw_len]

    # relocations
    relocs = []      # (offset, addend)  R_X86_64_RELATIVE
    symrels = []     # (offset, symbol name)
    for secname in ('.rela.dyn', '.rela.plt'):
        addr, off, size = secs[secname]
        for i in range(size // 24):
            r_off, r_info, r_add = struct.unpack_from('<QQq', d, off + i * 24)
            rtype = r_info & 0xffffffff
            sidx = r_info >> 32
            if rtype == 8:                       # R_X86_64_RELATIVE
                relocs.append((r_off, r_add))
            elif rtype in (6, 7):                # GLOB_DAT / JUMP_SLOT
                symrels.append((r_off, syms[sidx][0]))
            else:
                raise SystemExit('unhandled relocation type %d' % rtype)

    sym_kind = {
        'malloc': 'AQ_SYM_MALLOC',
        'free': 'AQ_SYM_FREE',
        'memcpy': 'AQ_SYM_MEMCPY',
        'memmove': 'AQ_SYM_MEMMOVE',
        'memset': 'AQ_SYM_MEMSET',
        '__cxa_finalize': 'AQ_SYM_NULL',
        '__gmon_start__': 'AQ_SYM_NULL',
        '_Jv_RegisterClasses': 'AQ_SYM_NULL',
    }

    out = []
    out.append('/* Generated by tools/gen_image.py -- do not edit. */')
    out.append('#include "shim.h"')
    out.append('')
    out.append('unsigned char aq_image[AQ_IMAGE_SIZE];')
    out.append('')
    out.append(c_array('aq_rodata', rodata, False))
    out.append('')
    out.append(c_array('aq_rwdata', rwdata, False))
    out.append('')
    out.append('const unsigned aq_rodata_addr = 0x%x;' % ro_addr)
    out.append('const unsigned aq_rodata_size = %d;' % len(rodata))
    out.append('const unsigned aq_rwdata_addr = 0x%x;' % rw_addr)
    out.append('const unsigned aq_rwdata_size = %d;' % len(rwdata))
    out.append('')
    out.append('const AqReloc aq_relocs[] = {')
    for off, add in relocs:
        out.append('  {0x%x, 0x%x},' % (off, add))
    out.append('};')
    out.append('const unsigned aq_num_relocs = %d;' % len(relocs))
    out.append('')
    out.append('const AqSymReloc aq_sym_relocs[] = {')
    for off, name in symrels:
        kind = sym_kind.get(name)
        if kind is None:
            raise SystemExit('unknown dynamic symbol %r' % name)
        out.append('  {0x%x, %s},' % (off, kind))
    out.append('};')
    out.append('const unsigned aq_num_sym_relocs = %d;' % len(symrels))
    out.append('')

    with open(OUT, 'w') as f:
        f.write('\n'.join(out))

    print('wrote', OUT)
    print('rodata %#x bytes, rwdata %#x bytes, relocs %d, symrelocs %d'
          % (len(rodata), len(rwdata), len(relocs), len(symrels)))
    assert IMAGE_SIZE == rw_addr + 0x9c8


if __name__ == '__main__':
    main()
