#!/usr/bin/env python3
"""Namespace an engine's global symbols so several engines can share a module.

Every engine used to be linked as its own WebAssembly module, so the same
helper names can appear in more than one engine (AqKanji2Koe and AqUsrDic
both define ``aqstr_append``, ``aq_image``, ...).  ``wasm-ld`` rejects
duplicate globals, and a static archive does not hide them.

Instead of rewriting wasm objects (``llvm-objcopy`` has no symbol rename for
wasm), the relocatable build compiles every translation unit twice:

1. pass 1 produces normal relocatable objects;
2. this script asks ``llvm-nm`` for every global the pass-1 objects define
   and writes a ``-include`` header that renames each one;
3. pass 2 recompiles with that header.

The public entry points listed in ``link/abis/<engine>.json`` are renamed to
short, stable names; everything else gets ``<prefix><original>``.  Because the
header is applied to every translation unit of the engine, definitions and
references stay consistent.
"""

from __future__ import annotations

import argparse
import json
import re
import subprocess
import sys
from pathlib import Path

# llvm-nm type letters for symbols defined in this object.
DEFINED_TYPES = frozenset("TDBRGWV")
IDENT = re.compile(r"^[A-Za-z_][A-Za-z0-9_]*$")
# Itanium C++ manglings are not source identifiers, so a #define cannot touch
# them.  Only one engine (AqUsrDic) uses C++, and its mangled names do not
# collide with the C engines.
MANGLED = re.compile(r"^_Z|^_GLOBAL__")
# C++ compiler-generated code calls these ABI helpers directly; renaming the
# definitions would break those references.  They are standard runtime names,
# not engine helpers, so leave them alone.  (AqKanji2Koe's C shim also defines
# __cxa_throw/_Unwind_Resume, and no other engine does.)
# __cxa_atexit, __cxa_guard_* and __dso_handle are emitted by the compiler for
# static construction and cannot be renamed.  __cxa_throw and friends are
# ordinary functions the engine's shim.c defines, so they get namespaced like
# every other engine helper.
RUNTIME_ABI = re.compile(
    r"^(__cxa_atexit$|__cxa_guard_|__cxa_pure_virtual$|__dso_handle$|__wasm_call_ctors$)"
)


def defined_symbols(objects: list[Path]) -> list[str]:
    if not objects:
        raise SystemExit("gen_prefix: no objects")
    proc = subprocess.run(
        ["llvm-nm", "--defined-only", "--extern-only", *map(str, objects)],
        check=True,
        text=True,
        capture_output=True,
    )
    names: set[str] = set()
    for line in proc.stdout.splitlines():
        parts = line.split()
        if len(parts) < 3:
            continue
        kind, name = parts[-2], parts[-1]
        if kind in DEFINED_TYPES:
            names.add(name)
    return sorted(names)


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--manifest", required=True, type=Path,
                        help="link/abis/<engine>.json")
    parser.add_argument("--objects", required=True, nargs="+", type=Path)
    parser.add_argument("--header", required=True, type=Path)
    parser.add_argument("--report", required=True, type=Path)
    args = parser.parse_args()

    manifest = json.loads(args.manifest.read_text())
    prefix: str = manifest["prefix"]
    api: dict[str, str] = manifest.get("api", {})
    if not prefix.endswith("_") or not IDENT.match(prefix + "x"):
        raise SystemExit(f"gen_prefix: invalid prefix {prefix!r}")

    defined = defined_symbols(args.objects)
    missing = sorted(set(api) - set(defined))
    if missing:
        raise SystemExit(
            f"gen_prefix: {args.manifest.name} maps symbols that are not defined: "
            + ", ".join(missing)
        )

    renames: dict[str, str] = {}
    skipped: list[str] = []
    for name in defined:
        if name in api:
            renames[name] = api[name]
        elif not IDENT.match(name):
            skipped.append(name)
        elif MANGLED.match(name) or RUNTIME_ABI.match(name):
            # Cannot be renamed at the source level (C++ mangling) or must keep
            # its standard name (compiler-generated ABI calls).  Report it so
            # the final link can be checked.
            skipped.append(name)
        else:
            renames[name] = prefix + name

    guard = "AQ_PREFIX_" + re.sub(r"[^A-Za-z0-9]", "_", prefix).upper()
    lines = [
        "/* Generated by link/tools/gen_prefix.py -- do not edit. */",
        f"#ifndef {guard}",
        f"#define {guard}",
        f"/* {manifest['engine']}: {len(renames)} renamed globals */",
    ]
    for old in sorted(renames):
        new = renames[old]
        if old != new:
            lines.append(f"#define {old} {new}")
    lines += [f"#endif /* {guard} */", ""]
    args.header.write_text("\n".join(lines))

    report = {
        "engine": manifest["engine"],
        "prefix": prefix,
        "renamed": dict(sorted(renames.items())),
        "skipped": skipped,
        "api": api,
    }
    args.report.write_text(json.dumps(report, indent=2, ensure_ascii=False) + "\n")
    print(
        f"  {manifest['engine']}: {len(renames)} symbols -> {prefix} "
        f"({len(api)} public), {len(skipped)} left alone"
    )
    if skipped:
        print("    left alone: " + ", ".join(skipped[:8])
              + (" ..." if len(skipped) > 8 else ""))
    return 0


if __name__ == "__main__":
    sys.exit(main())
