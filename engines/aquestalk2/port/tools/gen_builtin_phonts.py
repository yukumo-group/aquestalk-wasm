#!/usr/bin/env python3
"""Embed every AquesTalk2 phont into one C translation unit.

Order matches ``Aq2Preset`` / ``AQ2_PHONTS``, including ``aq_momo1.phont``.
"""

from __future__ import annotations

import sys
from pathlib import Path

# Same order as Aq2Preset in Yukw and Aqsh.h.
PHONTS = (
    "aq_yukkuri.phont",
    "aq_defo1.phont",
    "aq_f1c.phont",
    "aq_f3a.phont",
    "aq_huskey.phont",
    "aq_m4b.phont",
    "aq_mf1.phont",
    "aq_rb2.phont",
    "aq_rb3.phont",
    "aq_rm.phont",
    "aq_robo.phont",
    "aq_teto1.phont",
    "ar_f4.phont",
    "ar_m5.phont",
    "ar_mf2.phont",
    "ar_rm3.phont",
    "aq_momo1.phont",
)


def main() -> int:
    if len(sys.argv) != 3:
        print(f"usage: {sys.argv[0]} PHONT_DIR OUT.c", file=sys.stderr)
        return 2
    directory = Path(sys.argv[1])
    out = Path(sys.argv[2])
    blobs = []
    for name in PHONTS:
        path = directory / name
        data = path.read_bytes()
        if not data:
            raise SystemExit(f"{path} is empty")
        blobs.append((name, data))

    lines = [
        "/* Generated by tools/gen_builtin_phonts.py. Do not edit. */",
        "/* Aq2Preset order. aq_builtin_phont is the relocatable entry point. */",
        "",
        "typedef struct {",
        "    const unsigned char *data;",
        "    unsigned size;",
        "} AqBuiltinPhont;",
        "",
    ]
    for index, (name, data) in enumerate(blobs):
        lines.append(f"/* {name} */")
        lines.append(f"static const unsigned char aq_builtin_phont_bytes_{index}[] = {{")
        row = []
        for byte in data:
            row.append(f"0x{byte:02x}")
            if len(row) == 16:
                lines.append("    " + ",".join(row) + ",")
                row = []
        if row:
            lines.append("    " + ",".join(row) + ",")
        lines.append("};")
        lines.append("")

    lines.append("static const AqBuiltinPhont aq_builtin_phont_table[] = {")
    for index, (name, data) in enumerate(blobs):
        lines.append(
            f"    {{aq_builtin_phont_bytes_{index}, "
            f"sizeof aq_builtin_phont_bytes_{index}}}, /* {name} */"
        )
    lines += [
        "};",
        "",
        "const unsigned char *aq_builtin_phont(int aq_builtin_index, unsigned *aq_builtin_size)",
        "{",
        "    unsigned count = (unsigned)(sizeof aq_builtin_phont_table / sizeof aq_builtin_phont_table[0]);",
        "    if (aq_builtin_index < 0 || (unsigned)aq_builtin_index >= count)",
        "        return 0;",
        "    if (aq_builtin_size)",
        "        *aq_builtin_size = aq_builtin_phont_table[aq_builtin_index].size;",
        "    return aq_builtin_phont_table[aq_builtin_index].data;",
        "}",
        "",
    ]
    out.parent.mkdir(parents=True, exist_ok=True)
    out.write_text("\n".join(lines))
    total = sum(len(data) for _, data in blobs)
    print(f"  builtin phonts: {len(blobs)} files, {total} bytes -> {out}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
