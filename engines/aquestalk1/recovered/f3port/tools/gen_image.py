#!/usr/bin/env python3
"""Embed the data segments of aqtk1_lnx/lib64/f3/libAquesTalk.so.

The machine code is not embedded: it is recompiled from the Ghidra C output
(gen_decomp.py).  Only the non-executable PT_LOAD segments are copied into
`aq_image`, which mirrors the original virtual address space, and the dynamic
relocations are applied at startup.
"""
import os
import struct

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.abspath(os.path.join(HERE, '..', '..', '..'))
SO = os.path.join(ROOT, 'aqtk1_lnx', 'lib64', 'f3', 'libAquesTalk.so')
OUT = os.path.join(ROOT, 'recovered', 'f3port', 'src', 'image.c')

IMAGE_SIZE = 0x29060            # end of the RW PT_LOAD (0x25eb0 + memsz 0x31b0)


def parse_sections(d):
    e_shoff = struct.unpack_from('<Q', d, 0x28)[0]
    e_shentsize = struct.unpack_from('<H', d, 0x3a)[0]
    e_shnum = struct.unpack_from('<H', d, 0x3c)[0]
    e_shstrndx = struct.unpack_from('<H', d, 0x3e)[0]
    shstr = struct.unpack_from('<Q', d, e_shoff + e_shstrndx * e_shentsize + 0x18)[0]
    secs = {}
    for i in range(e_shnum):
        o = e_shoff + i * e_shentsize
        name_off = struct.unpack_from('<I', d, o)[0]
        name = d[shstr + name_off:].split(b'\0')[0].decode()
        addr, off, size = struct.unpack_from('<QQQ', d, o + 0x10)
        secs[name] = (addr, off, size)
    return secs


def parse_segments(d):
    e_phoff = struct.unpack_from('<Q', d, 0x20)[0]
    e_phentsize = struct.unpack_from('<H', d, 0x36)[0]
    e_phnum = struct.unpack_from('<H', d, 0x38)[0]
    segs = []
    for i in range(e_phnum):
        o = e_phoff + i * e_phentsize
        p_type = struct.unpack_from('<I', d, o)[0]
        p_flags = struct.unpack_from('<I', d, o + 4)[0]
        p_offset, p_vaddr, p_paddr, p_filesz, p_memsz = struct.unpack_from('<QQQQQ', d, o + 8)
        if p_type == 1 and p_filesz:
            segs.append((p_flags, p_offset, p_vaddr, p_filesz, p_memsz))
    return segs


def parse_dynsym(d, secs):
    _, dynsym_off, dynsym_size = secs['.dynsym']
    _, dynstr_off, _ = secs['.dynstr']
    out = []
    for i in range(dynsym_size // 24):
        st_name, st_info, st_other, st_shndx, st_value, st_size = struct.unpack_from(
            '<IBBHQQ', d, dynsym_off + i * 24)
        name = d[dynstr_off + st_name:].split(b'\0')[0].decode('latin-1') if st_name else ''
        out.append((name, st_value))
    return out


def c_array(name, data):
    lines = ['const unsigned char %s[%d] = {' % (name, len(data))]
    for i in range(0, len(data), 16):
        lines.append('  ' + ','.join('0x%02x' % b for b in data[i:i + 16]) + ',')
    lines.append('};')
    return '\n'.join(lines)


def main():
    d = open(SO, 'rb').read()
    secs = parse_sections(d)
    segs = parse_segments(d)
    syms = parse_dynsym(d, secs)

    # non-executable load segments
    data_segs = [(off, vaddr, filesz) for (flags, off, vaddr, filesz, memsz) in segs
                 if not (flags & 1)]
    for off, vaddr, filesz in data_segs:
        assert vaddr + filesz <= IMAGE_SIZE

    # relocations
    relocs = []      # (offset, addend)
    symrels = []     # (offset, symbol name)
    for secname in ('.rela.dyn', '.rela.plt'):
        _, off, size = secs[secname]
        for i in range(size // 24):
            r_off, r_info, r_add = struct.unpack_from('<QQq', d, off + i * 24)
            rtype = r_info & 0xffffffff
            sidx = r_info >> 32
            if rtype == 8:                       # R_X86_64_RELATIVE
                relocs.append((r_off, r_add))
            elif rtype in (6, 7):                # GLOB_DAT / JUMP_SLOT
                symrels.append((r_off, syms[sidx][0]))
            else:
                raise SystemExit('unhandled relocation type %d' % rtype)

    sym_kind = {
        'malloc': 'AQ_SYM_MALLOC',
        'free': 'AQ_SYM_FREE',
        'memcpy': 'AQ_SYM_MEMCPY',
        'memmove': 'AQ_SYM_MEMMOVE',
        'memset': 'AQ_SYM_MEMSET',
        'time': 'AQ_SYM_TIME',
        '__stack_chk_fail': 'AQ_SYM_STACK_CHK_FAIL',
        '__cxa_finalize': 'AQ_SYM_NULL',
        '__gmon_start__': 'AQ_SYM_NULL',
        '_ITM_deregisterTMCloneTable': 'AQ_SYM_NULL',
        '_ITM_registerTMCloneTable': 'AQ_SYM_NULL',
    }

    out = []
    out.append('/* Generated by tools/gen_image.py -- do not edit. */')
    out.append('#include "shim.h"')
    out.append('')
    out.append('unsigned char aq_image[AQ_IMAGE_SIZE];')
    out.append('')
    for i, (off, vaddr, filesz) in enumerate(data_segs):
        out.append(c_array('aq_seg_%d' % i, d[off:off + filesz]))
        out.append('')
    out.append('const AqSegment aq_segments[] = {')
    for i, (off, vaddr, filesz) in enumerate(data_segs):
        out.append('  {0x%x, aq_seg_%d, %d},' % (vaddr, i, filesz))
    out.append('};')
    out.append('const unsigned aq_num_segments = %d;' % len(data_segs))
    out.append('')
    out.append('const AqReloc aq_relocs[] = {')
    for off, add in relocs:
        out.append('  {0x%x, 0x%x},' % (off, add))
    out.append('};')
    out.append('const unsigned aq_num_relocs = %d;' % len(relocs))
    out.append('')
    out.append('const AqSymReloc aq_sym_relocs[] = {')
    for off, name in symrels:
        kind = sym_kind.get(name)
        if kind is None:
            raise SystemExit('unknown dynamic symbol %r' % name)
        out.append('  {0x%x, %s},' % (off, kind))
    out.append('};')
    out.append('const unsigned aq_num_sym_relocs = %d;' % len(symrels))
    out.append('')

    open(OUT, 'w').write('\n'.join(out))
    print('wrote', OUT)
    print('segments', [(hex(v), s) for _, v, s in data_segs])
    print('relocs %d, symrelocs %d, image %#x' % (len(relocs), len(symrels), IMAGE_SIZE))


if __name__ == '__main__':
    main()
