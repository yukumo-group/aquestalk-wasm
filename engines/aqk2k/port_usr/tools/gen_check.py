#!/usr/bin/env python3
"""Generate a Check-only AqUsrDic decomp unit (WIP diagnostics)."""
import os, re, importlib.util
HERE=os.path.dirname(os.path.abspath(__file__))
spec=importlib.util.spec_from_file_location('gd', os.path.join(HERE,'gen_decomp.py'))
gd=importlib.util.module_from_spec(spec); spec.loader.exec_module(gd)
ROOT=gd.ROOT
DECOMP=gd.DECOMP
OUT=os.path.join(ROOT,'port_usr','src','decomp_check.c')
WANT={'AqUsrDic_Check','FUN_0010cfb0','FUN_0010d740','FUN_0010d930'}
CHECK_BODY = r'''int AqUsrDic_Check(uint64_t surface, uint64_t yomi, int posCode)

{
  AqU16 y;
  AqU16 s;
  int err = 0;
  unsigned char b2 = 0, b3 = 0;
  long vec[3] = { 0, 0, 0 };

  AQU16_INIT(y);
  AQU16_INIT(s);
  FUN_0010d930((long *)&y, (byte *)(uintptr_t)yomi);
  FUN_0010d930((long *)&s, (byte *)(uintptr_t)surface);

  if (s.len == 0) {
    err = 0x12d;
  } else if (y.len == 0) {
    err = 0x12f;
  } else if (s.len < 0x20) {
    uint16_t *p = AQU16_DATA(s);
    for (uint64_t i = 0; i < s.len; i++) {
      unsigned int c = p[i];
      if (c < 0x7f || c == 0xa5 || c == 0x203e || (unsigned short)(c + 0x9f) < 0x3f) {
        err = 0x138;
        break;
      }
      if (c == 0x3000) {
        err = 0x139;
        break;
      }
    }
    if (err == 0) {
      uint16_t *p2 = AQU16_DATA(y);
      for (uint64_t i = 0; i < y.len; i++) {
        unsigned int c = p2[i];
        if (c == 0x27 || c == 0x2f || c == 0x5f || c == 0x2b || c == 0x30fc ||
            (c >= 0x3041 && c <= 0x3096) || (c >= 0x30a1 && c <= 0x30fa))
          continue;
        err = 0x136;
        break;
      }
      if (err == 0 && (posCode < 0 || (int)FUN_0010cfb0() <= posCode))
        err = 0x13a;
    }
  } else {
    err = 0x13b;
  }

  if (!AQU16_LOCAL(s))
    operator_delete(AQU16_DATA(s));
  if (!AQU16_LOCAL(y))
    operator_delete(AQU16_DATA(y));
  if (err != 0)
    FUN_00108cf0(err, 0);
  return err;
}
'''
def fix_image_strings(body):
    import re as _re
    def rep(m):
        return 'aqstr_append((char *)&local_88,(char *)(aq_image + 0x%x))' % (int(m.group(1),16)-0x100000)
    body = _re.sub(r'aqstr_append\(\(char \*\)&local_88,(0x1[0-9a-f]{5})\)', rep, body)
    body = body.replace('aqstr_replace(0x133220,', 'aqstr_replace((ulong)(uintptr_t)(aq_image + 0x33220),')
    return body

funcs=gd.read_funcs(DECOMP); datatypes=gd.load_datatypes(gd.DATATSV)
out=[]
for f in funcs:
    if f['name'] not in WANT: continue
    if f['name'] == 'AqUsrDic_Check':
        body = CHECK_BODY
    else:
        body=gd.normalize(f['name'],f['body'])
        body=gd.fix_usr_specifics(f['name'],body)
    body=fix_image_strings(body)
    out.append((f['name'],body))
alltext='\n'.join(b for _,b in out)
syms=set(re.findall(r'\b(DAT_[0-9a-f]+|_DAT_[0-9a-f]+|PTR_[A-Za-z0-9_]*_[0-9a-f]+|_UNK_[0-9a-f]+)\b',alltext))
strings=set(re.findall(r'\b(s_[A-Za-z0-9_]+_[0-9a-f]+)\b',alltext))
defs=[]
for s in sorted(strings):
    addr=int(s.rsplit('_',1)[1],16)-0x100000
    defs.append('#define %s ((unsigned char *)(aq_image + 0x%x))'%(s,addr))
for s in sorted(syms):
    addr=int(s.rsplit('_',1)[1],16)-0x100000
    typ,_=datatypes.get(s,('undefined1',1))
    if typ.startswith('pointer') or typ.endswith(' *'):
        defs.append('#define %s (*(undefined **)(aq_image + 0x%x))'%(s,addr))
    elif typ=='undefined8':
        defs.append('#define %s (*(undefined8 *)(aq_image + 0x%x))'%(s,addr))
    elif typ=='undefined4':
        defs.append('#define %s (*(undefined4 *)(aq_image + 0x%x))'%(s,addr))
    elif typ=='undefined2':
        defs.append('#define %s (*(undefined2 *)(aq_image + 0x%x))'%(s,addr))
    else:
        defs.append('#define %s (*(undefined1 *)(aq_image + 0x%x))'%(s,addr))
protos=[gd.split_sig(b)+';' for _,b in out]
with open(OUT,'w') as f:
    f.write('/* Generated by tools/gen_check.py -- WIP. */\n#include "shim.h"\n\n')
    f.write('\n'.join(defs)+'\n\n')
    f.write('\n'.join(protos)+'\n\n')
    for name,body in out:
        f.write('/* %s */\n%s\n'%(name,body))
print('wrote',OUT,'functions',len(out),'symbols',len(syms))
