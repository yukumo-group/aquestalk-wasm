#!/usr/bin/env python3
"""Embed libAqUsrDic.so.4.1 (PT_LOAD segments mapped at their VMAs)."""
import struct, os

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.abspath(os.path.join(HERE, '..', '..'))
SO = os.path.join(ROOT, 'aqk2k_lnx', 'lib', 'libAqUsrDic.so.4.1')
OUT = os.path.join(ROOT, 'port_usr', 'src', 'image.c')

d = open(SO, 'rb').read()

# Program headers
e_phoff = struct.unpack_from('<Q', d, 0x20)[0]
e_phentsize = struct.unpack_from('<H', d, 0x36)[0]
e_phnum = struct.unpack_from('<H', d, 0x38)[0]
loads = []
max_end = 0
for i in range(e_phnum):
    o = e_phoff + i * e_phentsize
    p_type = struct.unpack_from('<I', d, o)[0]
    if p_type != 1:  # PT_LOAD
        continue
    p_offset, p_vaddr, p_paddr, p_filesz, p_memsz, p_flags, p_align = struct.unpack_from('<QQQQQQQ', d, o + 8)
    loads.append((p_offset, p_vaddr, p_filesz, p_memsz))
    max_end = max(max_end, p_vaddr + p_memsz)

SIZE = (max_end + 0x1f) & ~0x1f
buf = bytearray(SIZE)
for off, vaddr, filesz, memsz in loads:
    buf[vaddr:vaddr + filesz] = d[off:off + filesz]

# .rela.dyn RELATIVE relocations
e_shoff = struct.unpack_from('<Q', d, 0x28)[0]
e_shentsize = struct.unpack_from('<H', d, 0x3a)[0]
e_shnum = struct.unpack_from('<H', d, 0x3c)[0]
e_shstrndx = struct.unpack_from('<H', d, 0x3e)[0]
shstr_off = struct.unpack_from('<Q', d, e_shoff + e_shstrndx * e_shentsize + 0x18)[0]
rel_off = rel_size = None
for i in range(e_shnum):
    o = e_shoff + i * e_shentsize
    name_off = struct.unpack_from('<I', d, o)[0]
    name = d[shstr_off + name_off:].split(b'\0')[0].decode()
    if name == '.rela.dyn':
        rel_off = struct.unpack_from('<Q', d, o + 0x18)[0]
        rel_size = struct.unpack_from('<Q', d, o + 0x20)[0]
        break

rels = []
for i in range(rel_size // 24):
    off, info, add = struct.unpack_from('<QQq', d, rel_off + i * 24)
    if (info & 0xffffffff) == 8:  # R_X86_64_RELATIVE
        rels.append((off, add))

with open(OUT, 'w') as f:
    f.write('/* Generated by tools/gen_image.py -- do not edit. */\n')
    f.write('#include "shim.h"\n\n')
    f.write('__attribute__((aligned(64))) unsigned char aq_image[0x%x] = {\n' % SIZE)
    for i in range(0, SIZE, 24):
        f.write('  ' + ','.join('0x%02x' % b for b in buf[i:i+24]) + ',\n')
    f.write('};\n\n')
    f.write('const AqReloc aq_relocs[] = {\n')
    for off, add in rels:
        f.write('  {0x%x, 0x%x},\n' % (off, add))
    f.write('};\n')
    f.write('const unsigned aq_num_relocs = %d;\n' % len(rels))
print('image bytes', hex(SIZE), 'relocs', len(rels), 'loads', loads)
